import { createFileRoute } from "@tanstack/react-router";
import { ArrowDown, BrainCircuit, Cpu, CloudOff, Droplets, Sigma, Thermometer, Waves } from "lucide-react";
import { Panel, PageHeader } from "@/components/Panel";
import { PrototypeBanner } from "@/components/PrototypeBanner";
import { SensorChart } from "@/components/SensorChart";
import { StatusBadge } from "@/components/StatusBadge";
import { useHistoricalData, usePrediction } from "@/hooks/useSensorData";
import { formatDateTime } from "@/utils/format";

export const Route = createFileRoute("/ai-prediction")({
  head: () => ({
    meta: [
      { title: "Edge AI Prediction — AIoT Aquaculture" },
      {
        name: "description",
        content:
          "Edge AI inference on the ESP32: temperature and TDS inputs produce predicted dissolved oxygen, biological delta and a water-condition classification.",
      },
      { property: "og:title", content: "Edge AI Prediction — AIoT Aquaculture" },
      {
        property: "og:description",
        content: "On-device ESP32 inference for dissolved oxygen prediction.",
      },
    ],
  }),
  component: AIPredictionPage,
});

const FLOW = [
  { label: "Temperature + TDS", icon: Thermometer, note: "Sensor inputs" },
  { label: "Edge AI Model", icon: BrainCircuit, note: "On-device inference" },
  { label: "Predicted DO", icon: Droplets, note: "mg/L output" },
  { label: "Delta Calculation", icon: Sigma, note: "Baseline DO − Predicted DO" },
  { label: "Water Condition", icon: Waves, note: "Classification" },
];

function AIPredictionPage() {
  const { data } = usePrediction(5000);
  const { data: history } = useHistoricalData(24);

  return (
    <div className="space-y-6">
      <PageHeader
        title="Edge AI Prediction"
        subtitle="The ESP32 performs local AI/ML inference for water-quality analysis without requiring continuous cloud-based computation."
        action={<StatusBadge label="Model Active" tone="normal" />}
      />
      <PrototypeBanner note="Prediction outputs shown here are generated by the mock service and mirror the structure of the on-device inference result." />

      <div className="grid gap-6 lg:grid-cols-2">
        <Panel title="Model Input" description="Values read from the physical sensors">
          <div className="space-y-3">
            <IoRow
              icon={Thermometer}
              label="Temperature (DS18B20)"
              value={data ? `${data.inputs.temperature.toFixed(1)} °C` : "—"}
            />
            <IoRow
              icon={Droplets}
              label="TDS"
              value={data ? `${data.inputs.tds} ppm` : "—"}
            />
          </div>
        </Panel>

        <Panel title="Model Output" description="Produced locally on the ESP32">
          <div className="space-y-3">
            <IoRow
              icon={BrainCircuit}
              label="Predicted Dissolved Oxygen"
              value={data ? `${data.outputs.predictedDO.toFixed(2)} mg/L` : "—"}
            />
            <IoRow
              icon={Sigma}
              label="Biological Delta (Δ)"
              value={data ? `${data.outputs.delta.toFixed(2)} mg/L` : "—"}
            />
            <div className="flex items-center justify-between rounded-lg border border-border bg-secondary/40 px-4 py-3">
              <span className="text-sm text-muted-foreground">Water-condition classification</span>
              <StatusBadge label={data?.outputs.condition ?? "…"} />
            </div>
          </div>
        </Panel>
      </div>

      <Panel title="Inference Flow" description="Sensor acquisition to water-condition assessment">
        <div className="flex flex-col items-stretch gap-2">
          {FLOW.map((step, idx) => (
            <div key={step.label} className="flex flex-col items-center gap-2">
              <div className="flex w-full max-w-xl items-center gap-3 rounded-xl border border-border-strong bg-secondary/40 px-4 py-3">
                <span className="flex size-9 items-center justify-center rounded-lg border border-primary/30 bg-primary/10 text-primary">
                  <step.icon className="size-4.5" />
                </span>
                <div>
                  <p className="text-sm font-medium">{step.label}</p>
                  <p className="text-xs text-muted-foreground">{step.note}</p>
                </div>
              </div>
              {idx < FLOW.length - 1 && <ArrowDown className="size-4 text-muted-foreground" />}
            </div>
          ))}
        </div>
      </Panel>

      <div className="grid gap-6 lg:grid-cols-3">
        <div className="panel flex items-start gap-3 p-5">
          <Cpu className="mt-0.5 size-5 text-primary" />
          <div>
            <p className="text-xs uppercase tracking-wider text-muted-foreground">
              Inference Location
            </p>
            <p className="mt-1 text-sm font-medium">{data?.inferenceLocation ?? "ESP32 Edge Device"}</p>
          </div>
        </div>
        <div className="panel flex items-start gap-3 p-5">
          <CloudOff className="mt-0.5 size-5 text-primary" />
          <div>
            <p className="text-xs uppercase tracking-wider text-muted-foreground">
              Cloud Dependency
            </p>
            <p className="mt-1 text-sm font-medium">
              {data?.cloudDependency ?? "Not Required for Inference"}
            </p>
          </div>
        </div>
        <div className="panel flex items-start gap-3 p-5">
          <BrainCircuit className="mt-0.5 size-5 text-primary" />
          <div>
            <p className="text-xs uppercase tracking-wider text-muted-foreground">Last Inference</p>
            <p className="mt-1 text-sm font-medium">
              {data ? formatDateTime(data.lastInferenceAt) : "—"}
            </p>
            <p className="text-xs text-muted-foreground">
              Execution time ≈ {data?.inferenceTimeMs ?? "—"} ms
            </p>
          </div>
        </div>
      </div>

      <Panel title="Prediction History" description="Predicted DO and biological delta over 24 hours">
        <SensorChart
          data={history}
          threshold={data?.deltaThreshold ?? 2}
          series={[
            { key: "predictedDO", name: "Predicted DO", color: "var(--color-chart-3)", unit: "mg/L" },
            { key: "delta", name: "Biological Delta", color: "var(--color-chart-4)", unit: "mg/L" },
          ]}
        />
      </Panel>
    </div>
  );
}

function IoRow({
  icon: Icon,
  label,
  value,
}: {
  icon: typeof Thermometer;
  label: string;
  value: string;
}) {
  return (
    <div className="flex items-center justify-between rounded-lg border border-border bg-secondary/40 px-4 py-3">
      <span className="flex items-center gap-2 text-sm text-muted-foreground">
        <Icon className="size-4 text-primary" />
        {label}
      </span>
      <span className="font-mono text-base">{value}</span>
    </div>
  );
}
